"""v28 (2026-09-21): FDA decisions BEFORE the project's earliest covered year.

The task
--------
Extend, add and analyse FDA decisions before the earliest year the project
covered when this session started. After v26/v27 that earliest year was
**1939** (``data/pre1965_fda_decisions.csv`` starts at 1939-02-09) with 1938
documented as a verified negative (``data/pre1938_determination.csv``).

So the honest question is not "what approvals happened in 1938" but:

  *is there anything at all before 1939 in any official record, and if not,
  what exactly proves it, and what governed drugs before the approval system
  existed?*

This builder answers that with four auditable tables. It invents no decisions.
Where the official record is silent, the silence is the published result, with
the evidence line that establishes it.

What this builder proves, from committed primary sources only
------------------------------------------------------------
1. **Application-number census below the boundary.** The unfiltered official
   Drugs@FDA application map (``Applications_all_types.txt``, 29,336 rows,
   SHA-manifested) contains **exactly two** applications numbered below
   NDA000552 - the application that carries the first recorded FDA drug
   approval action (1939-02-09): ``000004`` (NDA, PHARMICS) and ``000159``
   (NDA, LILLY). Every submission row for each is copied verbatim.
2. **1939-02-09 is the boundary.** In the official 1938-1964 Submissions
   window (1,215 rows) the earliest ``SubmissionStatusDate`` is
   ``1939-02-09 00:00:00`` on ApplNo 000552 (ORIG 1, AP, class 19), and there
   are **0 rows dated in 1938**.
3. **The openFDA payload block starts at 1939.** The committed payloads are
   ``decisions_1939.json`` .. ``decisions_1964.json`` - there is no 1938 file.
4. **The official Drugs@FDA Submissions table publishes approvals only.**
   Both committed windows are 100% ``AP`` (1,215/1,215 for 1939-1964 and
   10,753/10,753 for 1965-1979; submission types ORIG/SUPPL only). v27's site
   copy claimed the 1938-1964 register held "ORIG/AP plus RE, W, etc." and
   that "non-approval decisions (rejections/withdrawals) live" there. **That
   claim is not supported by the data and is corrected here.**
5. **The pre-1939 regulatory framework, year by year 1902-1938.** Statutes are
   quoted from the U.S. Statutes at Large via govinfo.gov and the FDA's own
   history pages. The decisive structural fact: the 1906 Food and Drugs Act
   (ch. 3915, 34 Stat. 768) contained **no pre-market approval requirement** -
   it prohibited adulterated/misbranded drugs in interstate commerce and put
   examinations in the Bureau of Chemistry, USDA. Federal pre-market
   *licensure* of a drug class existed earlier still, under the Biologics
   Control Act of 1902 (ch. 1378, 32 Stat. 728), where a virus/serum/toxin/
   antitoxin could not be sold unless made in an establishment holding an
   unrevoked license "issued by the Secretary of the Treasury". The general
   new-drug application was created by the 1938 FD&C Act (ch. 675,
   52 Stat. 1040), now codified at 21 U.S.C. 355(a).

Tables owned (rewritten deterministically on every run)
------------------------------------------------------
* ``data/pre1939_boundary_determination.csv``          (evidence lines)
* ``data/pre1939_application_census.csv``              (below-boundary apps)
* ``data/pre1939_regulatory_register_1902_1938.csv``   (37 year rows)
* ``data/pre1939_submission_status_census.csv``        (per-year status census)

Optional runner captures
------------------------
``fetch_jobs/drugsatfda_pre1939_census_v28.json`` (generated by
``scripts/gen_pre1939_census_job_v28.py``) captures the three things a
year-filtered window cannot: rows dated before 1939 anywhere in the 193,752-row
official table, rows with an unparseable status date (invisible to every year
filter), and the whole-table ``SubmissionStatus``/``SubmissionType`` census.
When ``data/raw/drugsatfda_pre1939_census_v28/manifest.json`` exists, the
builder re-hashes each capture against it and **aborts on any disagreement**
with the window-derived facts. Until it lands, the evidence rows say so
explicitly instead of overclaiming.

Fail-closed rules
-----------------
* SHA-256 of every committed input vs its runner manifest;
* ``Applications_all_types.txt`` must have exactly 29,336 applications;
* the below-boundary application set is *derived*, then compared with the
  captured census when present (mismatch aborts);
* 0 rows dated 1938, earliest date 1939-02-09 on ApplNo 000552, all statuses
  ``AP`` - any drift aborts;
* the v27 ``fda_1938_1964_full_submission_register.csv`` must reproduce the
  official extract row-for-row (key equality), else abort;
* no ticker, indication, corporate lineage, likelihood or probability column
  is written anywhere in any v28 table.
"""
