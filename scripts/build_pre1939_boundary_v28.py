    sha_1939 = sha256_file(PAYLOAD_DIR / "decisions_1939.json")
    if p1939.get("sha256") != sha_1939:
        print(f"FAIL: decisions_1939.json SHA drift ({sha_1939[:16]} != {str(p1939.get('sha256'))[:16]})")
