def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def read_tsv(path: Path) -> tuple[list[dict], list[str]]:
    with path.open(newline="", encoding="latin-1") as fh:
        rdr = csv.DictReader(fh, delimiter="\t")
        rows = list(rdr)
        return rows, list(rdr.fieldnames or [])


def read_csv(path: Path) -> list[dict]:
    with path.open(newline="", encoding="utf-8-sig") as fh:
        return list(csv.DictReader(fh))


def write_csv(path: Path, header: list[str], rows: list[dict]) -> None:
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=header, lineterminator="\n")
        w.writeheader()
        for r in rows:
            missing = [k for k in header if k not in r]
            if missing:
                raise SystemExit(f"{path.name}: row {r.get('row_id') or r.get('evidence_id') or r.get('census_id')} "
                                 f"missing keys {missing}")
            extra = [k for k in r if k not in header]
            if extra:
                raise SystemExit(f"{path.name}: unexpected keys {extra}")
            w.writerow(r)
    print(f"  wrote {path.relative_to(ROOT)}: {len(rows)} rows")


def rel_of(rec: dict) -> str:
    """Row id of an era-audit record, for the tracked-in cell."""
    return rec.get("row_id", "")


def manifest_index(path: Path) -> dict:
    """Map out-file -> manifest entry, for SHA re-verification."""
    if not path.exists():
        return {}
    m = json.loads(path.read_text(encoding="utf-8"))
    out: dict = {}
    for e in m.get("requests", []):
        if e.get("out"):
            out[e["out"]] = e
    return out


